"""Standard enumerations for the AegisPT Security Testing Engine.

These enums standardize scanner statuses, vulnerability severities, asset types,
and permission tiers across the entire platform.
"""

from enum import Enum


class ScanStatus(str, Enum):
    """Execution status of a scan job.

    Matches required platform lifecycle states:
    - SUCCESS: Scan executed, raw evidence collected, findings parsed.
    - FAILED: Tool execution failed or returned unrecoverable error.
    - CANCELLED: Scan manually cancelled prior to or during execution.
    - TIMEOUT: Scanner exceeded bounded runtime limit.
    - NEEDS_APPROVAL: Profile has potential impact and requires operator sign-off.
    """

    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    TIMEOUT = "TIMEOUT"
    NEEDS_APPROVAL = "NEEDS_APPROVAL"


class Severity(str, Enum):
    """Normalized vulnerability severity classification.

    Aligns with CVSS v3.1 / v4.0 qualitative ratings.
    """

    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AssetType(str, Enum):
    """Classification of target assets assessable by the engine."""

    IP_ADDRESS = "IP_ADDRESS"
    HOSTNAME = "HOSTNAME"
    CIDR_RANGE = "CIDR_RANGE"
    WEB_URL = "WEB_URL"
    PORT_SERVICE = "PORT_SERVICE"


class PermissionLevel(str, Enum):
    """Authorization tier required to execute a specific scan profile."""

    READ_ONLY = "READ_ONLY"      # Passive reconnaissance, DNS, public headers
    SAFE_AUDIT = "SAFE_AUDIT"    # Standard non-intrusive service discovery
    ACTIVE_PROBE = "ACTIVE_PROBE" # Active banner grabbing, baseline web testing
    INTRUSIVE = "INTRUSIVE"      # Fuzzing, parameter tampering (always requires approval)


class ImpactLevel(str, Enum):
    """Estimated operational impact of running a scan profile."""

    NONE = "NONE"       # Zero adverse operational impact expected
    LOW = "LOW"         # Minimal network/CPU overhead
    MEDIUM = "MEDIUM"   # May cause noticeable log noise or request spike
    HIGH = "HIGH"       # Potential service degradation; requires staging window


class OutputFormat(str, Enum):
    """Structured data formats generated by underlying security tools."""

    XML = "XML"         # E.g., Nmap XML (-oX)
    JSON = "JSON"       # E.g., OWASP ZAP API responses
    TEXT = "TEXT"       # Plain text / banner dump
    HAR = "HAR"         # HTTP Archive format
